#!/usr/bin/env python3
"""Synthesize a private NEON transform pair with a retained two-lane frame."""
import argparse
import difflib
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
BASE=ROOT/'.deps/flint/src/fft_small'


def replace_function(source,name,body):
    start=source.index('static void '+name+'(')
    brace=source.index('{',start)
    depth=1;end=brace+1
    while depth:
        depth+=(source[end]=='{')-(source[end]=='}');end+=1
    return source[:brace]+body+source[end:]


def base16(inverse,zero):
    lines=['{','    vec2d n=vec2d_set_d(Q->p), ninv=vec2d_set_d(Q->pinv);']
    lines += [f'    vec2d x{k}=vec2d_load(X+{2*k});' for k in range(8)]
    xs=','.join(f'x{k}' for k in range(8))
    def twiddle(level,index): return f'vec2d_set_d(Q->w2tab[{level}][{index}])'
    if zero:
        params=[twiddle('1','0'),twiddle('2','1' if inverse else '0'),twiddle('2','0' if inverse else '1')]
    else:
        var='j_mr' if inverse else 'j_r'
        params=[twiddle('j_bits',var)]
        for level in [1,2]:
            offsets=range((1<<level)-1,-1,-1) if inverse else range(1<<level)
            params += [twiddle(f'{level}+j_bits',f'{1<<level}*{var}+{i}') for i in offsets]
    prefix=f"    LENGTH8{'INV' if inverse else ''}_{'ZERO' if zero else 'ANY'}_J(vec2d,{xs},n,ninv,{','.join(params)});"
    if not inverse: lines.append(prefix)
    for r in range(4):
        if zero:
            idx=2*r
            values=[]
            for j in [idx,idx+1]:
                if j==0: values.append('-1.0' if inverse else '1.0')
                else:
                    bits=j.bit_length();rem=j-(1<<(bits-1))
                    if inverse: rem=(1<<(bits-1))-1-rem
                    values.append(f'Q->w2tab[{bits}][{rem}]')
            w='vec2d_set_d2('+','.join(values)+')'
        elif inverse:
            w=f'vec2d_set_d2(Q->w2tab[3+j_bits][8*j_mr+{7-2*r}],Q->w2tab[3+j_bits][8*j_mr+{6-2*r}])'
        else: w=f'vec2d_load(Q->w2tab[3+j_bits]+8*j_r+{2*r})'
        a,b=2*r,2*r+1
        lines+=['    {',f'        vec2d w={w};']
        if inverse:
            lines += [f'        LENGTH2INV_ANY_J(vec2d,x{a},x{b},n,ninv,w);',
                      f'        vec2d lo=vec2d_unpacklo(x{a},x{b}),hi=vec2d_unpackhi(x{a},x{b});',
                      f'        x{a}=lo;x{b}=hi;']
        else:
            lines += [f'        vec2d lo=vec2d_unpacklo(x{a},x{b}),hi=vec2d_unpackhi(x{a},x{b});',
                      '        lo=vec2d_reduce_to_pm1n(lo,n,ninv);',
                      '        hi=vec2d_mulmod(hi,w,n,ninv);',
                      f'        x{a}=vec2d_add(lo,hi);x{b}=vec2d_sub(lo,hi);']
        lines+=['    }']
    if inverse: lines.append(prefix)
    lines += [f'    vec2d_store(X+{2*k},x{k});' for k in range(8)]
    return '\n'.join(lines+['}'])


def base32(inverse,zero):
    kind='ifft' if inverse else 'fft'
    direction='REVERSE' if inverse else 'FORWARD'
    var='j_mr' if inverse else 'j_r'
    lines=['{']
    stage=[f"    RADIX_2_{direction}_PARAM_J_IS_{'Z' if zero else 'NZ'}(vec8d,Q"+
           (');' if zero else f',{var},j_bits);'),
           '    for (ulong i=0;i<16;i+=8) {',
           f"        RADIX_2_{direction}_MOTH_J_IS_{'Z' if zero else 'NZ'}(vec8d,X+i,X+16+i);",'    }']
    children=([f'    sd_{kind}_basecase_4_1(Q,X);',f'    sd_{kind}_basecase_4_0(Q,X+16,0,1);'] if zero else
        [f'    sd_{kind}_basecase_4_0(Q,X,2*{var}+{1 if inverse else 0},j_bits+1);',
         f'    sd_{kind}_basecase_4_0(Q,X+16,2*{var}+{0 if inverse else 1},j_bits+1);'])
    lines += children+stage if inverse else stage+children
    return '\n'.join(lines+['}'])


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--control',action='store_true',help='private copy of the unchanged transform')
    args=parser.parse_args()
    patches=[]
    for inverse in [False,True]:
        kind='ifft' if inverse else 'fft'
        source=(BASE/f'sd_{kind}.c').read_text()
        if not args.control:
            for zero in [True,False]:
                source=replace_function(source,f'sd_{kind}_basecase_4_{int(zero)}',base16(inverse,zero))
                source=replace_function(source,f'sd_{kind}_basecase_5_{int(zero)}',base32(inverse,zero))
        source=source.replace(f'void sd_{kind}_trunc(',f'void bf_sd_{kind}_trunc(')
        source=('/* Research fork: unchanged private control. */\n' if args.control else
                '/* Research fork: two-lane retained frame; generated by make_network_patch.py.\n   Public upstream transforms remain in their original translation units. */\n')+source
        filename=f'src/fft_small/bf_network_{kind}.c'
        patches.append(''.join(difflib.unified_diff([],source.splitlines(True),fromfile='/dev/null',tofile='b/'+filename)))
    original=(BASE/'mpn_mul_np2.c').read_text()
    source=original.replace('#include "fft_small.h"','#include "fft_small.h"\nvoid bf_sd_fft_trunc(sd_fft_ctx_t,double*,ulong,ulong,ulong);\nvoid bf_sd_ifft_trunc(sd_fft_ctx_t,double*,ulong,ulong);')
    source=source.replace('    sd_fft_trunc(', '    bf_sd_fft_trunc(').replace('    sd_ifft_trunc(', '    bf_sd_ifft_trunc(')
    path='src/fft_small/mpn_mul_np2.c'
    patches.append(''.join(difflib.unified_diff(original.splitlines(True),source.splitlines(True),fromfile='a/'+path,tofile='b/'+path)))
    name='network-control' if args.control else 'network-two-lane'
    (ROOT/f'patches/{name}.patch').write_text(''.join(patches))


if __name__=='__main__':main()
